--         未支付订单 30 分钟超时关闭，见 TradeOrderTimeoutScheduler。
--   发票  payment_invoice 支持类型 1 普通、2 专用（专票必填税号），同一订单唯一。
--   会员  member_user.member_level 存 REGULAR 等英文枚举，但门户 UserProfilePage
--         实际展示的是「普通会员 / 黄金VIP / 黑金SVIP」三档及其权益文案，
--         这里照抄门户，避免 AI 说的和买家看到的页面不一致。
--   入口  一律使用门户上的真实名称：我的订单 / 申请售后 / 申请发票 / 售后进度 /
--         领券中心 / 个人中心（资料与特权、我的券包）。不要写页面里不存在的入口。
--
-- 后台改过的条目不会被这个脚本覆盖：它只在全新库上执行一次。
-- =====================================================================

