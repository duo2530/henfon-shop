/**
 * 操作指南的章节内容。
 *
 * 拆成纯数据是为了让渲染层保持一份：新增模块只需往数组里加一项，排版、目录、搜索、
 * 锚点都由 OperationsGuidePage 统一处理。菜单名称、路由与权限编码均与后端
 * IdentityDataInitializer 的菜单初始化保持一致。
 */

export interface GuideStep {
  /** 步骤标题，用短语概括这一小步做什么。 */
  title: string;
  /** 具体做法与结果。 */
  detail: string;
}

export interface GuideSection {
  id: string;
  /** 所属分组，与侧边栏一级目录同名；通用说明归到「通用机制」与「排障」。 */
  group: string;
  title: string;
  /** 菜单路由地址，无独立菜单的章节留空。 */
  route?: string;
  /** 菜单权限编码，用于说明「看不到菜单」时该查什么。 */
  permission?: string;
  summary: string;
  capabilities?: string[];
  steps?: GuideStep[];
  notes?: string[];
}

